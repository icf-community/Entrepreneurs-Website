"""Stage adapters and objective scorers (AI-evaluation-plan §2, §3, §5).

Each adapter calls the production code for its stage: the grammar, the
grounding rules and the fake provider for interpretation; the privacy
boundary; the concept matcher; deterministic scoring for scores and
rankings. Nothing here re-implements a rule to make a check pass. Expected
answers are hand-written in datasets/*.jsonl, never generated by the code
under test.

A result is pass, fail or error; a case that could not run is never
counted as passed.
"""

