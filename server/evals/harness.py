DATASETS = Path(__file__).resolve().parent / "datasets"
SUITES = ("interpret", "adversarial", "adversarial_assess", "benign", "benign_domain",
         "scoring", "privacy", "concepts", "ranking")


@dataclass
class Result:
    case_id: str
    suite: str
    objectives: list[str]
    family: str
    critical: bool
    status: str  # pass | fail | error
    details: list[str] = field(default_factory=list)
    metrics: dict = field(default_factory=dict)


def load_cases(suite: str, *, split: str | None = None) -> list[dict]:
    """The suite's development+validation cases by default. split="heldout"
    reads <suite>.heldout.jsonl instead (gated by --release in __main__.py:
    held-out text must never appear in an ordinary run); a suite with no
    held-out file (nothing in datasets/*.py calls splits.partition on it)
    returns []."""
    if split == "heldout":
        path = DATASETS / f"{suite}.heldout.jsonl"
        if not path.exists():
            return []
    else:
        path = DATASETS / f"{suite}.jsonl"
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


# ─── Interpretation (O01, O02, O11) ─────────────────────────────────
_ALLOWED_FOR_CANDIDATES = {
    "recruiter": {"tool", "method", "area", "language", "free"},
    "network": None,
    "opportunities": {"tool", "method", "area", "language", "free", "location", "role_type"},
}


def interpret(case: dict, d: Dictionary, model: Callable[[dict], dict] | None = None) -> tuple[str, list[dict]]:
    """The executor's interpretation path, offline: minimise, grammar,
    otherwise one model answer (the fake unless `model` is given), then the
    same grounding rules the pipeline applies."""
    message = privacy.minimise(case["message"]).text.strip()
    mode = case["mode"]
    refused = screen(message)
    if refused:
        return refused, []
    ops = grammar_parse(message, mode, d)
    if ops is not None:
        return "apply", ops
    allowed = _ALLOWED_FOR_CANDIDATES[mode]
    candidates: dict[str, dict] = {}
    for m in d.find(message):
        concept = d.concepts[m.slug]
        if allowed is None or concept.kind in allowed:
            candidates.setdefault(m.slug, {"slug": m.slug, "label": concept.label, "kind": concept.kind, "start": m.start})
    spec = {"atoms": case.get("prior_atoms", [])}
    payload = {"mode": mode, "message": message, "current_criteria": spec["atoms"],
               "candidate_concepts": list(candidates.values()), "memory": []}
    answer = (model or _fake_interpret)(payload)
    return answer["decision"], ground_ops(answer.get("ops") or [], message, candidates, spec, mode, d)


def score_interpret(case: dict, decision: str, ops: list[dict]) -> list[str]:
    exp = case["expected"]
    problems: list[str] = []
    allowed = exp.get("decision_in") or [exp["decision"]]
    if decision not in allowed:
        problems.append(f"decision {decision!r}, expected {allowed}")
    adds = {o["concept"]: o for o in ops if o.get("op") == "add" and o.get("concept")}
    for slug, props in (exp.get("add") or {}).items():
        if decision not in ("apply", "mixed"):
            break
        op = adds.get(slug)
        if op is None:
            problems.append(f"missing criterion {slug}")
            continue
        if "required" in props and bool(op.get("required")) != props["required"]:
            problems.append(f"{slug}: required {op.get('required')}, expected {props['required']}")
        if props.get("negated") and not op.get("negated"):
            problems.append(f"{slug}: not negated")
        if props.get("group") and not op.get("group"):
            problems.append(f"{slug}: not grouped")
    for slug in exp.get("must_not_add") or []:
        if slug in adds:
            problems.append(f"added forbidden criterion {slug}")
    if exp.get("must_not_add_any") and adds:
        problems.append(f"added criteria when none were expected: {sorted(adds)}")
    # only_add/grouped describe what an apply/mixed decision must add; a
    # case whose decision_in also tolerates off_task/refuse (e.g. "the
    # off-task half of a mixed request may simply be discarded") is not
    # held to them when the model actually chose that other decision —
    # mirrors the same gating the "add" dict check above already uses.
    if decision in ("apply", "mixed"):
        if "only_add" in exp and set(adds) != set(exp["only_add"]):
            problems.append(f"added {sorted(adds)}, expected exactly {sorted(exp['only_add'])}")
        if exp.get("grouped"):
            groups = {adds[s].get("group") for s in exp["grouped"] if s in adds}
            if None in groups or len(groups) != 1:
                problems.append(f"{exp['grouped']}: not all grouped together (groups seen: {groups})")
    if exp.get("no_clear") and any(o.get("op") == "clear" for o in ops):
        problems.append("cleared earlier criteria")
    return problems


# ─── Assessor-stage grounding attacks (O01, O07) ────────────────────
def score_assess(case: dict) -> list[str]:
    """Drives Turn._bind — the exact static method the executor uses to
    ground a model's assessment verdict in the candidate's own evidence —
    or, for a schema_attack case, the strict output schema validation that
    runs before _bind ever sees the model's answer."""
    if "schema_attack" in case:
        try:
            schema_validate(case["schema_attack"], ASSESS_SCHEMA)
        except SchemaError:
            return []
        return ["malformed assessor output was NOT rejected by ASSESS_SCHEMA"]
    verdict = Turn._bind(case["raw"], case["ref_map"], set(case["free_ids"]))
    atoms = verdict.get("atoms") or {}
    problems: list[str] = []
    for atom_id, want in case["expected"].items():
        got = atoms.get(atom_id)
        if want is None:
            if got is not None:
                problems.append(f"{atom_id}: an unoffered atom id survived grounding ({got})")
            continue
        if got is None:
            problems.append(f"{atom_id}: dropped entirely, expected {want}")
            continue
        if got["state"] != want["state"]:
            problems.append(f"{atom_id}: state {got['state']!r}, expected {want['state']!r}")
        if got["evidence"] != want["evidence_ids"]:
            problems.append(f"{atom_id}: evidence {got['evidence']}, expected {want['evidence_ids']} "
                            f"(an id outside this candidate's own ref_map must never survive)")
    return problems


# ─── Scoring (O03, O05, O06, O11) ───────────────────────────────────
def _score_candidates(case: dict, candidates: dict, d: Dictionary) -> dict[str, tuple]:
    atoms = [Atom.from_json(a) for a in case["atoms"]]
    criteria = criteria_from_atoms(atoms)
    out = {}
    for rank, (name, cand) in enumerate(candidates.items()):
        evidence = cand["evidence"]
        states = {a.id: concept_state(a, evidence, d, substantial=len(evidence) >= 3) for a in atoms if a.concept}
        scored = score_candidate(case["mode"], criteria, states, task=cand.get("task"), depth=cand.get("depth"),
                                 transferable=bool(case.get("transferable")))
        out[name] = (scored, states, order_key(scored, rank) if scored else None)
    return out


def score_scoring(case: dict, d: Dictionary) -> list[str]:
    exp = case["expected"]
    results = _score_candidates(case, case["candidates"], d)
    problems: list[str] = []
    for name, want in (exp.get("scores") or {}).items():
        got = results[name][0].score if results[name][0] else None
        if got != want:
            problems.append(f"{name}: score {got}, expected {want}")
    for name, want in (exp.get("tiers") or {}).items():
        got = results[name][0].tier
        if got != want:
            problems.append(f"{name}: tier {got}, expected {want}")
    for name, bad in (exp.get("not_tier") or {}).items():
        if results[name][0].tier == bad:
            problems.append(f"{name}: presented as {bad}")
    for name, atom_states in (exp.get("states") or {}).items():
        for atom_id, want in atom_states.items():
            got = results[name][1][atom_id].state
            if got != want:
                problems.append(f"{name}.{atom_id}: state {got}, expected {want}")
    for group in exp.get("equal_scores") or []:
        values = {results[n][0].score for n in group}
        if len(values) != 1:
            problems.append(f"scores differ across {group}: {sorted(values)}")
    if exp.get("order"):
        got = sorted(exp["order"], key=lambda n: results[n][2])
        if got != exp["order"]:
            problems.append(f"order {got}, expected {exp['order']}")
    if exp.get("stable"):
        with_pool = _score_candidates(case, {**case["candidates"], **case.get("pool_additions", {})}, d)
        for name in exp["stable"]:
            if with_pool[name][0].score != results[name][0].score:
                problems.append(f"{name}: score changed when unrelated candidates joined the pool")
    return problems


# ─── Privacy (O07) ──────────────────────────────────────────────────
def score_privacy(case: dict) -> list[str]:
    ids = privacy.Identifiers.from_row(case.get("identifiers") or {})
    out = privacy.minimise(case["text"], ids).text
    problems = [f"leaked {s!r}" for s in case["must_remove"] if s in out]
    problems += [f"damaged {s!r}" for s in case["must_keep"] if s not in out]
    try:
        privacy.assert_clean(out, ids)
    except privacy.OutboundPolicyError as exc:
        problems.append(f"assembled payload still refused: {exc.kinds}")
    return problems


# ─── Concept extraction (O03) ───────────────────────────────────────
def score_concepts(case: dict, d: Dictionary) -> list[str]:
    found = set(d.positive(case["text"]))
    problems = [f"missed {s}" for s in case["positive"] if s not in found]
    problems += [f"false positive {s}" for s in case["absent"] if s in found]
    return problems


# ─── Retrieval and ranking (O04, O05) ───────────────────────────────
def _dcg(grades: list[int]) -> float:
    return sum((2 ** g - 1) / math.log2(i + 2) for i, g in enumerate(grades))


def rank(case: dict, d: Dictionary) -> list[tuple[str, object]]:
    """Exact-concept retrieval over the corpus (the protected leg of the
    SQL union), then deterministic scoring and ordering. Task and depth
    are read from the evidence the same way the fake assessor does."""
    query: set[str] = set()
    negated: set[str] = set()
    for a in case["atoms"]:
        target = d.expand_broad(a["concept"]) if a["kind"] == "area" else {a["concept"]}
        (negated if a.get("negated") else query).update(target)
    issued = {}
    for name, evidence in case["corpus"].items():
        concepts = {c for e in evidence if e.get("polarity", "positive") == "positive" for c in e["concepts"]}
        any_mention = {c for e in evidence for c in e["concepts"]}
        if concepts & negated:
            continue
        if any_mention & query:
            work = [e for e in evidence if e["kind"] in ("cv_project", "cv_role", "github_repo")]
            level = "strong" if len(work) >= 3 else "some" if work else "none"
            issued[name] = {"evidence": evidence, "task": level, "depth": level}
    scored = _score_candidates(case, issued, d)
    ordered = sorted((n for n in scored if scored[n][0]), key=lambda n: scored[n][2])
    return [(n, scored[n][0]) for n in ordered]


def score_ranking(case: dict, d: Dictionary) -> tuple[list[str], dict]:
    ranked = rank(case, d)
    names = [n for n, _ in ranked]
    grades = case["grades"]
    relevant = {n for n, g in grades.items() if g >= 2}
    top = names[:10]
    recall = len(relevant & set(top)) / len(relevant) if relevant else 1.0
    ideal = sorted(grades.values(), reverse=True)[:10]
    ndcg = _dcg([grades.get(n, 0) for n in top]) / _dcg(ideal) if ideal else 1.0
    problems: list[str] = []
    gates = case.get("gates", {})
    if recall < gates.get("recall_at_10", 0):
        problems.append(f"recall@10 {recall:.2f} < {gates['recall_at_10']}")
    if ndcg < gates.get("ndcg_at_10", 0):
        problems.append(f"nDCG@10 {ndcg:.2f} < {gates['ndcg_at_10']}")
    by_name = dict(ranked)
    for name in case.get("never_meets", []):
        if name in by_name and by_name[name].tier == "meets":
            problems.append(f"{name} presented as meeting every must-have")
    if case.get("top1") and (not names or names[0] != case["top1"]):
        problems.append(f"top result {names[0] if names else None}, expected {case['top1']}")
    return problems, {"recall_at_10": round(recall, 4), "ndcg_at_10": round(ndcg, 4), "ranked": top}


# ─── Statistics (§7) ────────────────────────────────────────────────
def wilson(passed: int, total: int, z: float = 1.96) -> tuple[float, float]:
    if total == 0:
        return (0.0, 0.0)
    p = passed / total
    denom = 1 + z * z / total
    centre = (p + z * z / (2 * total)) / denom
    half = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total * total)) / denom
    return (round(max(0.0, centre - half), 4), round(min(1.0, centre + half), 4))


def run_suite(suite: str, model: Callable[[dict], dict] | None = None, *, split: str | None = None) -> list[Result]:
    d = load_dictionary()
    results: list[Result] = []
    for case in load_cases(suite, split=split):
        base = dict(case_id=case["id"], suite=suite, objectives=case.get("objectives", []),
                    family=case.get("family", ""), critical=bool(case.get("critical")))
        try:
            metrics: dict = {}
            if suite in ("interpret", "adversarial", "benign", "benign_domain"):
                decision, ops = interpret(case, d, model if suite in ("interpret", "adversarial", "benign") else None)
                problems = score_interpret(case, decision, ops)
                metrics = {"decision": decision, "ops": len(ops)}
            elif suite == "adversarial_assess":
                problems = score_assess(case)
            elif suite == "scoring":
                problems = score_scoring(case, d)
            elif suite == "privacy":
                problems = score_privacy(case)
            elif suite == "concepts":
                problems = score_concepts(case, d)
            elif suite == "ranking":
                problems, metrics = score_ranking(case, d)
            else:
                raise ValueError(suite)
            results.append(Result(**base, status="fail" if problems else "pass", details=problems, metrics=metrics))
        except Exception as exc:  # noqa: BLE001 — an error is reported, never counted as a pass
            results.append(Result(**base, status="error", details=[f"{type(exc).__name__}: {exc}"]))
    return results
